"""Run the SteerDistill benchmark + smoke eval and write measured reports.

Usage: python3 scripts/steer_distill_eval.py --report-dir ~/system2-eval-reports/reports
Only measured values are written; pytest/ruff output is captured verbatim.
"""

import argparse
import json
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sys2.distill import (  # noqa: E402
    evaluate_flip_rate,
    export_steer_distill_shards,
    load_trajectory_pairs,
    run_corrective_distill_smoke,
    split_by_session,
)


def synth(d: Path, n: int) -> None:
    d.mkdir(parents=True, exist_ok=True)
    with (d / "synthetic.jsonl").open("w") as fh:
        for i in range(n):
            fh.write(json.dumps({
                "timestamp": f"2026-11-20T00:00:00.{i:04d}Z", "session_id": f"s{i % 50}",
                "stage": ["pre_guard", "post_guard", "rollback"][i % 3], "context": f"ctx {i}",
                "rejected_call": {"tool": "bash", "args": {"cmd": f"rm {i}"}},
                "guard_reason": f"reason {i}",
                "eventual_passing_fix": None if i % 10 == 0 else {"tool": "edit", "args": {"p": i}},
            }) + "\n")


def throughput(n: int = 1000) -> dict:
    runs = []
    for _ in range(2):
        with tempfile.TemporaryDirectory() as td:
            d = Path(td) / "t"
            synth(d, n)
            t0 = time.perf_counter()
            pairs, stats = load_trajectory_pairs(d)
            tr, va = split_by_session(pairs)
            rep = export_steer_distill_shards(tr, va, Path(td) / "out")
            gold = [i % 6 for i in range(len(pairs))]
            evaluate_flip_rate([gold, gold], [gold, gold], gold)
            runs.append({"seconds": time.perf_counter() - t0, "lines": stats.lines,
                         "valid_pairs": stats.valid_pairs, "unpaired": stats.unpaired_rejections,
                         "converted_mlx": sum(rep["mlx_lora"].values()), "converted_dpo": sum(rep["dpo"].values())})
    return {"runs": runs}


def sh(cmd: list[str]) -> dict:
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    # Portable output: swap the home dir for ~ and the interpreter path for python3.
    home = str(Path.home())
    out = (p.stdout + p.stderr).replace(home, "~").strip().splitlines()
    return {"cmd": " ".join(["python3" if c == sys.executable else c for c in cmd]), "returncode": p.returncode, "tail": out[-12:]}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--report-dir", required=True)
    args = ap.parse_args()
    out = Path(args.report_dir).expanduser()
    tp = throughput()
    smoke = run_corrective_distill_smoke()
    tests = sh([sys.executable, "-m", "pytest", "-q", "tests/test_steer_distill.py", "tests/test_lazy_backbone.py"])
    lint = sh(["ruff", "check", "sys2/distill", "tests/test_steer_distill.py", "scripts/steer_distill_eval.py"])
    res = {"throughput_1000_lines": tp, "smoke": smoke, "pytest": tests, "ruff": lint}
    (out / "STEER_DISTILL_FLYWHEEL_EVAL.json").write_text(json.dumps(res, indent=2) + "\n")

    lo, m = smoke["lora"], smoke["deletion_mask"]
    t_ok = all(r["seconds"] <= 2.0 for r in tp["runs"])
    conv_ok = all(r["converted_mlx"] == r["valid_pairs"] == r["converted_dpo"] for r in tp["runs"])
    drop_ok = lo["heldout_corrective_loss_after"] < lo["heldout_corrective_loss_before"]
    def ctrl_ok(a):
        f = a["clean_control_flip"]
        return f["flip_rate"] <= f["noise_floor"] + 0.02
    P = lambda b: "PASS" if b else "FAIL"  # noqa: E731
    md = f"""# SteerDistill Flywheel Eval (Goldmine Build 1)

Generated by `scripts/steer_distill_eval.py` in branch `feat/t_b8751573-steer-distill` of `~/system2`.
All numbers measured on this machine; smoke data is **synthetic** (hashed bag-of-words linear student,
{smoke['weights_total']} weights), not real agent trajectories. Flip-rate repeats use simulated logit jitter (0.5 std); margins are large so measured noise floor is 0.0 here, meaning the control check is effectively 'no flips + 2%'.

## Scorecard

| Q | Metric | Result | Verdict |
|---|---|---|---|
| Gate Q2 | corrupt-line crashes / session leakage | covered by `tests/test_steer_distill.py::test_gate1_*` (0 crashes, disjoint sessions over 5 seeds) | {P(tests['returncode']==0)} |
| Gate Q4 | mutation of `models/system2*.pt` / `.best_metric*` | hash+mtime unchanged (`test_gate2_*`) | {P(tests['returncode']==0)} |
| Primary Q1 | valid pairs converted to MLX-LoRA + DPO | {tp['runs'][0]['converted_mlx']}/{tp['runs'][0]['valid_pairs']} and {tp['runs'][0]['converted_dpo']}/{tp['runs'][0]['valid_pairs']} | {P(conv_ok)} |
| Primary Q1 | held-out corrective loss (LoRA) | {lo['heldout_corrective_loss_before']:.4f} -> {lo['heldout_corrective_loss_after']:.4f} | {P(drop_ok)} |
| Secondary Q2 | clean-control flip vs noise floor (LoRA) | flip {lo['clean_control_flip']['flip_rate']:.4f}, floor {lo['clean_control_flip']['noise_floor']:.4f}, degraded {lo['clean_control_flip']['degraded_flips']:.2f} | {P(ctrl_ok(lo))} |
| Secondary Q3 | 1,000 lines ingest+export+flip eval | {tp['runs'][0]['seconds']:.4f}s, {tp['runs'][1]['seconds']:.4f}s (limit 2.0s) | {P(t_ok)} |

## Corrective smoke: LoRA vs Deletion Tuning mask

| Arm | changed/trained params | held-out corrective loss | clean-control loss | clean-control flip (floor) | held-out corrective flip: improved / degraded |
|---|---|---|---|---|---|
| LoRA r={smoke['rank']} | {lo['trainable_or_changed_params']} | {lo['heldout_corrective_loss_before']:.4f} -> {lo['heldout_corrective_loss_after']:.4f} | {lo['clean_control_loss_before']:.4f} -> {lo['clean_control_loss_after']:.4f} | {lo['clean_control_flip']['flip_rate']:.4f} ({lo['clean_control_flip']['noise_floor']:.4f}) | {lo['corrective_heldout_flip']['improved_flips']:.1f} / {lo['corrective_heldout_flip']['degraded_flips']:.1f} |
| Deletion mask {smoke['mask_fraction']:.0%} | {m['trainable_or_changed_params']} zeroed | {m['heldout_corrective_loss_before']:.4f} -> {m['heldout_corrective_loss_after']:.4f} | {m['clean_control_loss_before']:.4f} -> {m['clean_control_loss_after']:.4f} | {m['clean_control_flip']['flip_rate']:.4f} ({m['clean_control_flip']['noise_floor']:.4f}) | {m['corrective_heldout_flip']['improved_flips']:.1f} / {m['corrective_heldout_flip']['degraded_flips']:.1f} |

Note: the scorecard-style 0.05% budget is below one weight at this size, so a {smoke['mask_fraction']:.0%} budget is used.

## Raw command output

pytest (`{tests['cmd']}`), rc={tests['returncode']}:
```
{chr(10).join(tests['tail'])}
```

ruff (`{lint['cmd']}`), rc={lint['returncode']}:
```
{chr(10).join(lint['tail'])}
```
"""
    (out / "STEER_DISTILL_FLYWHEEL_EVAL.md").write_text(md)


if __name__ == "__main__":
    main()
